#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum UiLang {
    En = 0,
    Ru = 1,
}

impl UiLang {
    pub fn from_u8(v: u8) -> Self {
        match v {
            1 => Self::Ru,
            _ => Self::En,
        }
    }

    pub fn is_ru(self) -> bool {
        self == Self::Ru
    }

    pub fn toggle(self) -> Self {
        match self {
            Self::En => Self::Ru,
            Self::Ru => Self::En,
        }
    }
}

